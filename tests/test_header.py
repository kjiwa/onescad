def test_header_lists_provenance_doc_needs_and_licenses_in_order(tmp_path: Path) -> None:
    lib = tmp_path / "lib"
    lib.mkdir()
    (lib / "LICENSE").write_text("Permission is hereby granted.\n\nNo warranty.\n")
    header = Header(
        version="1.2.3",
        origin=Origin("a/m.scad", "https://example.org/a", "abc", True),
        doc="// A model.",
        fonts=["Liberation Sans"],
        external_files=['"part.stl"'],
        presets="m.json",
        licenses=[License(lib / "LICENSE", ())],
    )
    text = render(header, [tmp_path])
    assert text.endswith("\n\n")
    assert text.splitlines() == [
        "// Generated by onescad 1.2.3. Do not edit; edit the source instead.",
        "// Source: a/m.scad",
        "// Remote: https://example.org/a",
        "// Commit: abc+dirty",
        "//",
        "// A model.",
        "//",
        "// Fonts required: Liberation Sans",
        '// External files read at render time: "part.stl"',
        "// Presets: m.json holds this model's Customizer presets; keep it next to this file.",
        "//",
        "// License: lib",
        "// Permission is hereby granted.",
        "//",
        "// No warranty.",
        "",
    ]


def test_a_bare_header_is_one_line() -> None:
    bare = Header("1", None, "", [], [], None, [])
    assert render(bare, []) == (
        "// Generated by onescad 1. Do not edit; edit the source instead.\n\n"
    )


def test_the_nearest_ancestor_license_wins(tmp_path: Path) -> None:
    (tmp_path / "LICENSE").write_text("outer")
    inner = tmp_path / "lib" / "deep"
    inner.mkdir(parents=True)
    (tmp_path / "lib" / "LICENSE-MIT").write_text("mit")
    (tmp_path / "lib" / "COPYING").write_text("copying")
    (tmp_path / "lib" / "README").write_text("not a license")
    assert [p.name for p in nearest_licenses(inner / "a.scad")] == ["COPYING", "LICENSE-MIT"]
    assert [p.name for p in nearest_licenses(tmp_path / "b.scad")] == ["LICENSE"]


def test_collect_groups_files_by_license_and_reports_unlicensed(tmp_path: Path) -> None:
    (tmp_path / "lib").mkdir()
    (tmp_path / "lib" / "LICENSE").write_text("x")
    a, b = tmp_path / "lib" / "a.scad", tmp_path / "lib" / "b.scad"
    c = tmp_path / "c.scad"
    found, unlicensed = collect([a, b, c])
    assert [(f.path.name, f.covers) for f in found] == [("LICENSE", (a, b))]
    assert unlicensed == [c]


def test_component_is_relative_to_the_first_containing_root(tmp_path: Path) -> None:
    root = tmp_path / "repo"
    assert component(root / "lib" / "BOSL2" / "LICENSE", [root]) == "lib/BOSL2"
    assert component(root / "LICENSE", [root]) == "repo"
    assert component(Path("/elsewhere/pkg/LICENSE"), [root]) == "pkg"
