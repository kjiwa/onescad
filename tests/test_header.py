import subprocess
from pathlib import Path

import pytest

from onescad.header import Header, Origin, find_origin, normalize_remote, render
from onescad.licenses import License, collect, component, nearest_licenses


@pytest.mark.parametrize(
    ("url", "expected"),
    [
        ("git@github.com:kjiwa/onescad.git", "https://github.com/kjiwa/onescad"),
        ("https://github.com/kjiwa/onescad.git", "https://github.com/kjiwa/onescad"),
        ("https://user:token@github.com/kjiwa/onescad", "https://github.com/kjiwa/onescad"),
        ("ssh://git@github.com:22/kjiwa/onescad.git", "https://github.com/kjiwa/onescad"),
        ("git://example.org/a/b.git/", "https://example.org/a/b"),
        ("/srv/repos/model", "/srv/repos/model"),
    ],
)
def test_normalize_remote(url: str, expected: str) -> None:
    assert normalize_remote(url) == expected


def git(directory: Path, *args: str) -> None:
    config = ["-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false"]
    command = ["git", "-C", str(directory), *config, *args]
    subprocess.run(command, check=True, capture_output=True)  # noqa: S603


def test_origin_outside_a_repository_is_none(tmp_path: Path) -> None:
    main = tmp_path / "m.scad"
    main.write_text("")
    assert find_origin(main) is None


def test_origin_names_path_remote_commit_and_dirtiness(tmp_path: Path) -> None:
    repo = tmp_path.resolve()
    (repo / "sub").mkdir()
    main = repo / "sub" / "m.scad"
    main.write_text("x = 1;\n")
    git(repo, "init", "-q")
    git(repo, "remote", "add", "origin", "git@github.com:kjiwa/models.git")
    git(repo, "add", ".")
    git(repo, "commit", "-q", "-m", "init")
    clean = find_origin(main)
    assert clean is not None
    assert (clean.path, clean.remote, clean.dirty) == (
        "sub/m.scad",
        "https://github.com/kjiwa/models",
        False,
    )
    assert len(clean.commit) == 40
    main.write_text("x = 2;\n")
    dirty = find_origin(main)
    assert dirty is not None and dirty.dirty


